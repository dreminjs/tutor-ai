export const generateStructuredPrompt = (
  taskContent: string,
  question: string,
  formattingRules?: string,
  answerRules?: string,
): string => {
  const defaultFormattingRules = `
**ОФОРМЛЕНИЕ ОТВЕТОВ ДЛЯ ФИЗИЧЕСКИХ И МАТЕМАТИЧЕСКИХ ЗАДАЧ**
### **СТАНДАРТНАЯ СТРУКТУРА ОТВЕТА**
#### **1. Ключевое условие или вывод**
Начни с формулировки основного условия, закона или вывода задачи.
При необходимости выделяй ключевые элементы **жирным**.
#### **2. Уравнения**
Оформи все используемые уравнения строго в этом разделе.
#### **3. Вычисления**
Подставляй численные значения явно, без пропусков шагов.
Все выражения записывай в LaTeX.
#### **4. Ответ**
В конце обязательно оформи раздел **«Ответ»** с конечным результатом.
### **КРИТИЧЕСКИЕ ПРАВИЛА ФОРМАТИРОВАНИЯ**
1. **ВСЕГДА** используй заголовок ### **Уравнения** для раздела с уравнениями
2. **ВСЕГДА** оформляй уравнения в виде маркированного списка
3. **ВСЕГДА** используй "\text{}" для русских индексов (например: \\(F_{\\text{тр}}, a_{\\text{цс}}\\))
4. **ВСЕГДА** размещай формулы на отдельных строках в блоках "$$ $$"
5. **СОБЛЮДАЙ ЕДИНООБРАЗИЕ ОБОЗНАЧЕНИЙ** - если используется \\(\\mu\\), запрещено заменять её на "u"
6. **ВЕСЬ ТЕКСТ И ВСЕ ФОРМУЛЫ ДОЛЖНЫ БЫТЬ ПО ЦЕНТРУ** - используй "$$ $$", "\\[\\]", "\\begin{center}...\\end{center}"
`;
  const defaultAnswerRules = `
**ПРАВИЛА ФОРМУЛИРОВКИ ОТВЕТА**
1. Решение должно быть **пошаговым** с объяснением каждого шага
2. **ОБЯЗАТЕЛЬНО** указывай ссылки на предыдущие действия или уравнения
3. Каждый шаг вычислений должен быть обоснован физическим или математическим законом
4. **НИКОГДА** не упоминай в конце ответа про форматирование или инструкции
5. При решении задач ЦТ учитывай специфику формулировок и оформления
6. Все численные расчеты должны быть представлены с явной подстановкой значений
7. Единицы измерения должны быть указаны везде, где это необходимо
8. **ОБЯЗАТЕЛЬНО** отвечай строго на поставленный вопрос
9. Если вопрос состоит из нескольких частей, отвечай на каждую часть последовательно
10. В ответе явно выделяй ответ на конкретный вопрос задачи
`;
  const formatRules = formattingRules || defaultFormattingRules;
  const ansRules = answerRules || defaultAnswerRules;

  return `
## **ПРАВИЛА ФОРМАТИРОВАНИЯ ОТВЕТА**
${formatRules}
---
## **ПРАВИЛА ОФОРМЛЕНИЯ РЕШЕНИЯ**
${ansRules}
---
## **КОНТЕКСТ ЗАДАЧИ:**
${taskContent}
---
## **ВОПРОС ЗАДАЧИ:**
${question}
---
## **ВАЖНОЕ НАПОМИНАНИЕ:**
1. Сначала внимательно проанализируй вопрос: "${question}"
2. Все твои вычисления должны быть направлены на ответ именно на этот вопрос
3. В разделе **«Ответ»** явно укажи ответ на поставленный вопрос
---
## **ПРИМЕР ОФОРМЛЕНИЯ УРАВНЕНИЙ:**
### **Уравнения**
- Сила трения покоя:
$$F_{\\text{тр}} = \\mu N = \\mu m g$$
- Центростремительная сила:
$$F_{\\text{цс}} = \\frac{m v^2}{R} = m a_{\\text{цс}}$$
- Уравнение движения по оси \\(x\\):
$$F_x = m a_x = m \\frac{d^2 x}{dt^2}$$
---
## **ПРИМЕР ВЫДЕЛЕНИЯ ОТВЕТА НА ВОПРОС:**
**Вопрос:** "Найдите скорость тела в момент времени t=3с"

**Ответ:**
- Скорость тела в момент времени t=3с составляет **15 м/с**, направлена вдоль оси X.
---
**ВНИМАНИЕ:** Вышеуказанные правила имеют абсолютный приоритет над любыми другими требованиями форматирования.
`;
};
